// Download the two fonts into fonts/ so visitors' browsers never contact Google (see docs/privacy.md).
// Both are under the SIL Open Font License, which allows this; their licenses are saved alongside.
// To change fonts or weights: edit CSS_URL, run this, check the site, commit fonts/.
//   node scripts/vendor-fonts.js
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";

const CSS_URL = "https://fonts.googleapis.com/css2?family=Atkinson+Hyperlegible:wght@400;700&family=Bricolage+Grotesque:opsz,wght@12..96,600;12..96,800&display=swap";
const SUBSETS = ["latin", "latin-ext"];
const LICENSES = {
  "atkinson-hyperlegible": "https://raw.githubusercontent.com/google/fonts/main/ofl/atkinsonhyperlegible/OFL.txt",
  "bricolage-grotesque": "https://raw.githubusercontent.com/google/fonts/main/ofl/bricolagegrotesque/OFL.txt",
};
const out = path.resolve(import.meta.dirname, "../fonts");
// Google sends woff2 only to browsers it recognizes.
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36";

const get = async (url, as) => {
  const res = await fetch(url, {headers: {"user-agent": UA}});
  if (!res.ok) throw new Error(`${res.status} from ${url}`);
  return as === "bytes" ? Buffer.from(await res.arrayBuffer()) : res.text();
};

const css = await get(CSS_URL);
const faces = [...css.matchAll(/\/\* ([\w-]+) \*\/\s*(@font-face \{[^}]+\})/g)]
  .filter(([, subset]) => SUBSETS.includes(subset))
  .map(([, subset, rule]) => ({subset, rule, url: rule.match(/url\((\S+?)\)/)[1],
    family: rule.match(/font-family: '([^']+)'/)[1], weight: rule.match(/font-weight: (\d+)/)[1]}));
if (!faces.length) throw new Error("No @font-face rules found: has Google changed its CSS?");

// A variable font serves several weights from one file: name it after all of them.
const weights = {};
for (const f of faces) (weights[f.url] ??= []).push(f.weight);
const slug = s => s.toLowerCase().replace(/ /g, "-");
const fileFor = f => `${slug(f.family)}-${[...new Set(weights[f.url])].join("-")}-${f.subset}.woff2`;

fs.rmSync(out, {recursive: true, force: true});
fs.mkdirSync(out);
const saved = new Set();
for (const f of faces) {
  const name = fileFor(f);
  if (saved.has(name)) continue;
  const bytes = await get(f.url, "bytes");
  fs.writeFileSync(path.join(out, name), bytes);
  saved.add(name);
  console.log(`${name}  ${(bytes.length / 1024).toFixed(0)} KB  sha256 ${crypto.createHash("sha256").update(bytes).digest("hex")}`);
}
fs.writeFileSync(path.join(out, "fonts.css"),
  `/* Generated by scripts/vendor-fonts.js from ${CSS_URL} */\n` +
  faces.map(f => `/* ${f.subset} */\n${f.rule.replace(f.url, `./${fileFor(f)}`)}`).join("\n") + "\n");
for (const [name, url] of Object.entries(LICENSES)) fs.writeFileSync(path.join(out, `${name}-OFL.txt`), await get(url));
console.log(`Wrote fonts/fonts.css and the licenses.`);

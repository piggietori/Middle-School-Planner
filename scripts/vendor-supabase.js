// Download a pinned, single-file browser build of @supabase/supabase-js into src/vendor/.
// The site has no build step, so the library is checked in. To upgrade: change VERSION, run this, test, commit.
//   node scripts/vendor-supabase.js
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";

const VERSION = "2.118.0"; // pick a release at least two weeks old
const url = `https://esm.sh/@supabase/supabase-js@${VERSION}/es2022/supabase-js.bundle.mjs`;
const out = path.resolve(import.meta.dirname, "../src/vendor/supabase-js.js");

const res = await fetch(url);
if (!res.ok) throw new Error(`${res.status} from ${url}`);
let code = await res.text();
const sha = crypto.createHash("sha256").update(code).digest("hex");

// esm.sh imports Node polyfills the library only feature-detects; use the real globals instead (undefined in browsers).
const polyfills = [
  [/^import __Process\$ from "\/node\/process\.mjs";\n/m, "const __Process$ = globalThis.process;\n"],
  [/^import \{ Buffer as __Buffer\$ \} from "\/node\/buffer\.mjs";\n/m, "const __Buffer$ = globalThis.Buffer;\n"],
];
for (const [re, sub] of polyfills) {
  if (!re.test(code)) throw new Error(`Expected ${re} in the bundle. Check the new version by hand.`);
  code = code.replace(re, sub);
}
const left = code.match(/^import .* from "\/.*$/m);
if (left) throw new Error(`The bundle still imports from esm.sh: ${left[0]}`);

fs.mkdirSync(path.dirname(out), {recursive: true});
fs.writeFileSync(out, `/* @supabase/supabase-js ${VERSION} (MIT License, https://github.com/supabase/supabase-js)
   Built by esm.sh: ${url}
   sha256 of the download: ${sha}
   Generated by scripts/vendor-supabase.js. Do not edit. */
${code}`);
console.log(`Wrote ${path.relative(process.cwd(), out)} (${(code.length / 1024).toFixed(0)} KB), sha256 ${sha}`);
